"""Procedural city map for a fictional world.

The road network is generated by **recursive subdivision** (a Parish-style city
generator): a land area is repeatedly split by streets — the first, longest cuts
become arterials, later cuts become local streets — and every leaf polygon is a
city block. Regular rectangular buildings and named compounds (小区) are placed
inside the blocks, and the model names the roads, metro lines/stations, bus
routes/stops, parks, water, districts, compounds and cities.

Everything is deterministic from (country, city), so the same setting always
yields the same map. The model's *raw input* is what gets persisted (not the
built geometry), so the map is warped exactly once per build. Rendered by
Leaflet on a simple CRS, so it pans and zooms like a real map.
"""
