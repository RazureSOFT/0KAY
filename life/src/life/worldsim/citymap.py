def _rects_from_poly(warped_poly, rng):
    """Regular (axis-aligned) building footprints inside a block's bounds."""
    xs = [p[0] for p in warped_poly]
    ys = [p[1] for p in warped_poly]
    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
    width, height = maxx - minx, maxy - miny
    if width < 16 or height < 16:
        return []
    nx = 1 if width < 52 else rng.choice([1, 2])
    ny = 1 if height < 52 else rng.choice([1, 2])
    margin, gap = 6.0, 5.0
    rects = []
    for gx in range(nx):
        for gy in range(ny):
            x0 = minx + margin + (width - 2 * margin) * gx / nx + gap / 2
            x1 = minx + margin + (width - 2 * margin) * (gx + 1) / nx - gap / 2
            y0 = miny + margin + (height - 2 * margin) * gy / ny + gap / 2
            y1 = miny + margin + (height - 2 * margin) * (gy + 1) / ny - gap / 2
            if x1 - x0 < 7 or y1 - y0 < 7:
                continue
            rects.append([[round(x0, 1), round(y0, 1)], [round(x1, 1), round(y0, 1)],
                          [round(x1, 1), round(y1, 1)], [round(x0, 1), round(y1, 1)]])
    return rects


