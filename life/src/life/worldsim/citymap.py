def _seed(text: str) -> int:
    return int(hashlib.md5(str(text or "world").encode("utf-8")).hexdigest()[:8], 16)


def _float(value, default: float) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _clamp(value: float, low: float, high: float) -> float:
    return max(low, min(high, value))


# --------------------------------------------------------------------- geometry
def _area(poly) -> float:
    total = 0.0
    for i in range(len(poly)):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % len(poly)]
        total += x1 * y2 - x2 * y1
    return abs(total) / 2.0


def _centroid(poly) -> list[float]:
    a = cx = cy = 0.0
    for i in range(len(poly)):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % len(poly)]
        cross = x1 * y2 - x2 * y1
        a += cross
        cx += (x1 + x2) * cross
        cy += (y1 + y2) * cross
    if abs(a) < 1e-9:
        return [sum(p[0] for p in poly) / len(poly), sum(p[1] for p in poly) / len(poly)]
    return [cx / (3 * a), cy / (3 * a)]


def _side(p, a, b) -> float:
    return (b[0] - a[0]) * (p[1] - a[1]) - (b[1] - a[1]) * (p[0] - a[0])


def _clip(poly, a, b, keep_left):
    out = []
    n = len(poly)
    for i in range(n):
        p, q = poly[i], poly[(i + 1) % n]
        sp, sq = _side(p, a, b), _side(q, a, b)
        pin = sp >= 0 if keep_left else sp <= 0
        qin = sq >= 0 if keep_left else sq <= 0
        if pin:
            out.append(p)
        if pin != qin and (sp - sq) != 0:
            t = sp / (sp - sq)
            out.append([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t])
    return out


def _cut(poly, a, b):
    """The segment where the line through a,b crosses the polygon boundary."""
    pts = []
    n = len(poly)
    for i in range(n):
        p, q = poly[i], poly[(i + 1) % n]
        sp, sq = _side(p, a, b), _side(q, a, b)
        if sp * sq < 0 and (sp - sq) != 0:
            t = sp / (sp - sq)
            pts.append([p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t])
    uniq = []
    for p in pts:
        if not any(abs(p[0] - u[0]) < 0.6 and abs(p[1] - u[1]) < 0.6 for u in uniq):
            uniq.append(p)
    return uniq


def _densify(points, step: float = 42.0):
    out = []
    for i in range(len(points) - 1):
        a, b = points[i], points[i + 1]
        distance = math.hypot(b[0] - a[0], b[1] - a[1])
        count = max(1, int(distance / step))
        for k in range(count):
            t = k / count
            out.append([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t])
    out.append(list(points[-1]))
    return out


def _warp_xy(x, y, width, height, phase):
    """A smooth, deterministic distortion that curves straight streets."""
    u, v = x / width, y / height
    return (x + 18 * math.sin(math.tau * v * 1.6 + phase) + 9 * math.sin(math.tau * v * 3.3 + phase * 1.7),
            y + 16 * math.sin(math.tau * u * 1.5 + phase * 1.3) + 8 * math.sin(math.tau * u * 3.1 + phase * 0.7))


def _warp_path(points, width, height, phase):
    return [[round(wx, 1), round(wy, 1)] for wx, wy in
            (_warp_xy(x, y, width, height, phase) for x, y in _densify(points))]


def _warp_map(world_map: dict, width: int, height: int, phase: float) -> dict:
    """Bend the linear features (streets, roads, water, lines, places).

    Blocks / parks / compounds are generated already in warped space and stay
    rectangular, so they are not touched here.
    """
    for street in world_map.get("streets", []):
        street["points"] = _warp_path(street["points"], width, height, phase)
    for road in world_map.get("roads", []):
        road["points"] = _warp_path(road["points"], width, height, phase)
    for lake in world_map.get("lakes", []):
        lake["points"] = _warp_ring(lake["points"], width, height, phase)
        lake["label"] = list(_warp_xy(lake["label"][0], lake["label"][1], width, height, phase))
    for river in world_map.get("rivers", []):
        river["points"] = _warp_path(river["points"], width, height, phase)
    for district in world_map.get("districts", []):
        district["x"], district["y"] = (round(v, 1) for v in _warp_xy(district["x"], district["y"], width, height, phase))
    for loc in world_map.get("locations", []):
        loc["x"], loc["y"] = (round(v, 1) for v in _warp_xy(loc["x"], loc["y"], width, height, phase))
    for building in world_map.get("named_buildings", []):
        building["x"], building["y"] = (round(v, 1) for v in _warp_xy(building["x"], building["y"], width, height, phase))
    for line in world_map.get("metro", []) + world_map.get("bus", []):
        line["points"] = _warp_path(line["points"], width, height, phase)
        for stop in line.get("stations", []):
            stop["x"], stop["y"] = (round(v, 1) for v in _warp_xy(stop["x"], stop["y"], width, height, phase))
        line["stops"] = line.get("stations", [])
    return world_map


def _warp_ring(points, width, height, phase):
    dense = []
    n = len(points)
    for i in range(n):
        a, b = points[i], points[(i + 1) % n]
        dense.append(a)
        dense.append([(a[0] + b[0]) / 2, (a[1] + b[1]) / 2])
    return [[round(wx, 1), round(wy, 1)] for wx, wy in
            (_warp_xy(x, y, width, height, phase) for x, y in dense)]


def _subdivide(poly, depth, rng, streets, arterials, max_depth, top_levels, min_area):
    if depth <= 0 or len(poly) < 3 or _area(poly) < min_area:
        return [poly]
    minx = min(p[0] for p in poly); maxx = max(p[0] for p in poly)
    miny = min(p[1] for p in poly); maxy = max(p[1] for p in poly)
    vertical = (maxx - minx) >= (maxy - miny)
    theta = (math.pi / 2 if vertical else 0.0) + rng.uniform(-0.4, 0.4)
    direction = [math.cos(theta), math.sin(theta)]
    normal = [-direction[1], direction[0]]
    center = _centroid(poly)
    span = (maxy - miny) if vertical else (maxx - minx)
    off = rng.uniform(-0.18, 0.18) * span
    point = [center[0] + normal[0] * off, center[1] + normal[1] * off]
    a = [point[0] - direction[0] * 1400, point[1] - direction[1] * 1400]
    b = [point[0] + direction[0] * 1400, point[1] + direction[1] * 1400]
    left = _clip(poly, a, b, True)
    right = _clip(poly, a, b, False)
    if len(left) < 3 or len(right) < 3:
        return [poly]
    seg = _cut(poly, a, b)
    if len(seg) >= 2:
        segment = [[round(seg[0][0], 1), round(seg[0][1], 1)], [round(seg[1][0], 1), round(seg[1][1], 1)]]
        kind = "highway" if depth >= max_depth - 1 else ("arterial" if depth >= max_depth - 3 else "street")
        streets.append({"points": segment, "kind": kind})
        if kind != "street":
            arterials.append(segment)
    args = (depth - 1, rng, streets, arterials, max_depth, top_levels, min_area)
    return _subdivide(left, *args) + _subdivide(right, *args)


