def _dist_point_segment(px, py, ax, ay, bx, by) -> float:
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + dx * t), py - (ay + dy * t))


def _in_water(x, y, lakes, rivers, margin: float = 32.0) -> bool:
    """True if (x,y) is on a lake or within a river's channel."""
    for lake in lakes:
        lx, ly = lake["label"]
        if math.hypot(x - lx, y - ly) < lake.get("r", 80) * 0.9:
            return True
    for river in rivers:
        points = river["points"]
        for i in range(len(points) - 1):
            if _dist_point_segment(x, y, points[i][0], points[i][1], points[i + 1][0], points[i + 1][1]) < margin:
                return True
    return False


def _convex_hull(points):
    """Andrew's monotone chain — an organic outline for a compound."""
    pts = sorted({(round(p[0], 2), round(p[1], 2)) for p in points})
    if len(pts) < 3:
        return [list(p) for p in pts]

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower = []
    for p in pts:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
            lower.pop()
        lower.append(p)
    upper = []
    for p in reversed(pts):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
            upper.pop()
        upper.append(p)
    return [list(p) for p in (lower[:-1] + upper[:-1])]


def _dedupe(items, key):
    seen, out = set(), []
    for item in items:
        value = key(item)
        if value and value in seen:
            continue
        if value:
            seen.add(value)
        out.append(item)
    return out


def _split_into(poly, count, rng):
    """Split a polygon into ~count organic pieces by recursive bisection."""
    pieces = [poly]
    guard = 0
    while len(pieces) < count and guard < count * 4:
        guard += 1
        index = max(range(len(pieces)), key=lambda k: _area(pieces[k]))
        target = pieces[index]
        minx = min(p[0] for p in target); maxx = max(p[0] for p in target)
        miny = min(p[1] for p in target); maxy = max(p[1] for p in target)
        vertical = (maxx - minx) >= (maxy - miny)
        theta = (math.pi / 2 if vertical else 0.0) + rng.uniform(-0.5, 0.5)
        direction = [math.cos(theta), math.sin(theta)]
        normal = [-direction[1], direction[0]]
        center = _centroid(target)
        span = (maxy - miny) if vertical else (maxx - minx)
        off = rng.uniform(-0.16, 0.16) * span
        point = [center[0] + normal[0] * off, center[1] + normal[1] * off]
        a = [point[0] - direction[0] * 1400, point[1] - direction[1] * 1400]
        b = [point[0] + direction[0] * 1400, point[1] + direction[1] * 1400]
        left = _clip(target, a, b, True)
        right = _clip(target, a, b, False)
        if len(left) < 3 or len(right) < 3:
            break
        pieces[index:index + 1] = [left, right]
    return pieces


def _route_along_streets(stations, streets):
    """Follow the street network between stations instead of drawing rulers."""
    nodes: dict = {}
    adjacency: dict = {}

    def node_id(x, y):
        key = (int(round(x / 7)), int(round(y / 7)))
        nodes.setdefault(key, [x, y])
        return key

    for segment in streets:
        points = segment.get("points", [])
        for i in range(len(points) - 1):
            a = node_id(points[i][0], points[i][1])
            b = node_id(points[i + 1][0], points[i + 1][1])
            if a == b:
                continue
            adjacency.setdefault(a, set()).add(b)
            adjacency.setdefault(b, set()).add(a)
    if not nodes:
        return [[round(s["x"], 1), round(s["y"], 1)] for s in stations]

    def nearest(x, y):
        return min(nodes, key=lambda k: (nodes[k][0] - x) ** 2 + (nodes[k][1] - y) ** 2)

    def path_between(s, t):
        from collections import deque
        queue = deque([s])
        previous = {s: None}
        while queue:
            current = queue.popleft()
            if current == t:
                break
            for neighbor in adjacency.get(current, ()):
                if neighbor not in previous:
                    previous[neighbor] = current
                    queue.append(neighbor)
        if t not in previous:
            return None
        path, cursor = [], t
        while cursor is not None:
            path.append(nodes[cursor])
            cursor = previous[cursor]
        path.reverse()
        return path

    routed = []
    for index, station in enumerate(stations):
        if index == 0:
            routed.append([round(station["x"], 1), round(station["y"], 1)])
            continue
        previous = stations[index - 1]
        path = path_between(nearest(previous["x"], previous["y"]), nearest(station["x"], station["y"]))
        if path:
            routed.extend([[round(x, 1), round(y, 1)] for x, y in path])
        routed.append([round(station["x"], 1), round(station["y"], 1)])
    return routed


def _fallback_metro(width, height, network=None):
    """A small network: several east-west / north-south / diagonal lines."""
    lines = []

    def add(index, stations):
        points = _route_along_streets(stations, network) if network else [[s["x"], s["y"]] for s in stations]
        lines.append({"name": f"地铁{index + 1}号线", "color": _METRO_COLORS[index % len(_METRO_COLORS)],
                      "points": points, "stations": stations, "stops": stations})

    index = 0
    for frac, count in ((0.20, 12), (0.40, 14), (0.60, 14), (0.80, 12)):
        y = height * frac
        add(index, [{"name": f"站{k + 1}", "x": round(60 + (width - 120) * k / (count - 1), 1), "y": round(y, 1)}
                    for k in range(count)])
        index += 1
    for frac, count in ((0.24, 11), (0.5, 11), (0.76, 11)):
        x = width * frac
        add(index, [{"name": f"站{k + 1}", "x": round(x, 1), "y": round(60 + (height - 120) * k / (count - 1), 1)}
                    for k in range(count)])
        index += 1
    add(index, [{"name": f"站{k + 1}", "x": round(90 + (width - 180) * k / 9, 1),
                 "y": round(80 + (height - 160) * k / 9, 1)} for k in range(10)])
    return lines


def _fallback_bus(index, network=None):
    names = list(index.keys())
    if len(names) < 2:
        return []
    routes = []
    for r, start in enumerate((0, 1, 2)):
        rotated = names[start:] + names[:start]
        stops = [{"name": n, "x": round(index[n][0], 1), "y": round(index[n][1], 1)} for n in rotated[:8]]
        if len(stops) < 2:
            continue
        points = _route_along_streets(stops, network) if network else [[s["x"], s["y"]] for s in stops]
        routes.append({"name": f"公交{11 + r}路", "color": _BUS_COLORS[r % len(_BUS_COLORS)],
                       "points": points, "stations": stops, "stops": stops})
    return routes


def _landmass(seed, width, height, vertices: int = 96):
    rng = random.Random(seed)
    harmonics = [(rng.uniform(0.05, 0.12), rng.choice([2, 3, 4, 5]), rng.uniform(0, math.tau)) for _ in range(4)]
    cx, cy = width / 2, height / 2
    points = []
    for index in range(vertices):
        angle = math.tau * index / vertices
        radius = 1.0 + sum(amp * math.sin(freq * angle + phase) for amp, freq, phase in harmonics)
        points.append([round(cx + math.cos(angle) * width * 0.40 * radius, 1),
                       round(cy + math.sin(angle) * height * 0.40 * radius, 1)])
    return points, (cx, cy)


def build_nation(*, country, city, provinces, cities, width=WIDTH, height=HEIGHT):
    """A nationwide overview: the land, its provinces and cities, and the roads
    between them. Deterministic per country/city."""
    seed = _seed(f"nation|{country}|{city}")
    rng = random.Random(seed)
    land, center = _landmass(seed, width, height)
    names = [str(p).strip() for p in (provinces or []) if str(p).strip()]
    if not names:
        names = [p + "省" for p in rng.sample(_BUILDING_PREFIX, 6)]
    count = max(3, min(len(names), 8))
    province_shapes = []
    for k, piece in enumerate(_split_into(land, count, rng)):
        name = names[k] if k < len(names) else f"{country}{k + 1}省"
        province_shapes.append({"name": str(name)[:16],
                                "points": [[round(p[0], 1), round(p[1], 1)] for p in piece],
                                "label": _centroid(piece)})
    province_shapes = _dedupe(province_shapes, lambda p: p["name"])

    city_defs = []
    if isinstance(cities, list):
        for entry in cities[:12]:
            if isinstance(entry, dict) and entry.get("name"):
                city_defs.append({"name": str(entry["name"])[:16],
                                  "x": round(_clamp(_float(entry.get("x"), center[0]), 40, width - 40), 1),
                                  "y": round(_clamp(_float(entry.get("y"), center[1]), 40, height - 40), 1),
                                  "capital": bool(entry.get("capital"))})
    city_defs = _dedupe(city_defs, lambda c: c["name"])
    if not city_defs:
        city_defs.append({"name": (city or "首府")[:16], "x": round(center[0], 1), "y": round(center[1], 1), "capital": True})
        for prov in province_shapes:
            city_defs.append({"name": prov["name"].replace("省", "")[:16],
                              "x": prov["label"][0], "y": prov["label"][1], "capital": False})
    if city_defs and not any(c["capital"] for c in city_defs):
        city_defs[0]["capital"] = True

    capital = next((c for c in city_defs if c["capital"]), city_defs[0] if city_defs else None)
    routes = []
    if capital:
        for c in city_defs:
            if c is capital:
                continue
            routes.append({"points": [[capital["x"], capital["y"]],
                                      [round((capital["x"] + c["x"]) / 2 + rng.uniform(-24, 24), 1),
                                       round((capital["y"] + c["y"]) / 2 + rng.uniform(-24, 24), 1)],
                                      [c["x"], c["y"]]]})
    return {"kind": "nation", "title": (country or city or "全国") + "地图",
            "width": width, "height": height, "country": country, "city": city,
            "land": land, "provinces": province_shapes, "cities": city_defs, "routes": routes}


def _location_edges(locations) -> list[list[str]]:
    """Connect the story's places into a walkable graph (nearest-unvisited chain),
    so the runtime can move actors between them regardless of map kind."""
    ids = [loc["id"] for loc in locations if loc.get("id")]
    if len(ids) < 2:
        return []
    position = {loc["id"]: (loc["x"], loc["y"]) for loc in locations if loc.get("id")}
    edges: list[list[str]] = []
    current = ids[0]
    remaining = set(ids[1:])
    while remaining:
        nxt = min(remaining, key=lambda i: (position[i][0] - position[current][0]) ** 2
                  + (position[i][1] - position[current][1]) ** 2)
        edges.append([current, nxt])
        remaining.discard(nxt)
        current = nxt
    return edges


def build_city(*, country, city, districts, water, roads, metro, bus, parks, compounds, buildings,
               names, locations, actors, title, width=WIDTH, height=HEIGHT):
    seed = _seed(f"{country}|{city}")
    rng = random.Random(seed)
    phase = (seed % 628) / 100.0
    margin = 60

    lakes = _norm_lakes(water, rng, width, height)
    rivers = _norm_rivers(water, rng, width, height)

    placed = []
    for loc in locations:
        placed.append({**loc,
                       "x": round(_clamp(_float(loc.get("x"), width / 2), 60, width - 60), 1),
                       "y": round(_clamp(_float(loc.get("y"), height / 2), 60, height - 60), 1),
                       "lat": None, "lng": None})
    index = {loc["name"]: (loc["x"], loc["y"]) for loc in placed if loc.get("name")}

    def warp(x, y):
        return _warp_xy(x, y, width, height, phase)

    def wpoly(poly):
        dense = []
        n = len(poly)
        for i in range(n):
            a, b = poly[i], poly[(i + 1) % n]
            dense.append(a)
            dense.append([(a[0] + b[0]) / 2, (a[1] + b[1]) / 2])
        return [list(warp(x, y)) for x, y in dense]

    warped_rivers = [{"points": _warp_path(rv["points"], width, height, phase)} for rv in rivers]
    warped_lakes = [{"label": list(warp(lk["label"][0], lk["label"][1])), "r": lk.get("r", 80)} for lk in lakes]

    # --- road network: recursive subdivision --------------------------------
    root = [[margin, margin], [width - margin, margin], [width - margin, height - margin], [margin, height - margin]]
    streets: list[dict] = []
    arterials: list[list] = []
    leaves = _subdivide(root, 6, rng, streets, arterials, max_depth=6, top_levels=2, min_area=_MIN_BLOCK_AREA)
    ring = [[width / 2 + math.cos(math.tau * k / 60) * width * 0.33,
             height / 2 + math.sin(math.tau * k / 60) * height * 0.33] for k in range(60)]
    streets.append({"points": ring, "kind": "highway"})
    street_only = [seg for seg in streets if seg.get("kind") == "street"]
    majors = [seg for seg in streets if seg.get("kind") != "street"]
    major_names = _road_names(len(majors), rng)
    generated_roads = [{"name": major_names[i], "kind": seg.get("kind", "arterial"), "points": seg["points"]}
                       for i, seg in enumerate(majors)]

    # --- compounds (小区) ----------------------------------------------------
    compound_defs = _norm_compounds(compounds, names, width, height)
    if not compound_defs:
        for i in range(5):
            angle = -math.pi / 2 + math.tau * i / 5
            compound_defs.append({"name": "", "x": width / 2 + math.cos(angle) * width * 0.27,
                                  "y": height / 2 + math.sin(angle) * height * 0.28, "r": 140})
    compound_names = _compound_names(len(compound_defs), rng)
    for i, entry in enumerate(compound_defs):
        if not entry.get("name"):
            entry["name"] = compound_names[i]
    compound_defs = _dedupe(compound_defs, lambda d: d["name"])

    def nearest_compound(cx, cy):
        return min(range(len(compound_defs)),
                   key=lambda i: (compound_defs[i]["x"] - cx) ** 2 + (compound_defs[i]["y"] - cy) ** 2)

    blocks: list[dict] = []
    park_shapes: list[dict] = []
    member_points = [[] for _ in compound_defs]
    used_names: set = set()
    park_pick = set(rng.sample(range(len(leaves)), min(max(6, len(leaves) // 7), len(leaves)))) if leaves else set()
    for idx, leaf in enumerate(leaves):
        wleaf = wpoly(leaf)
        cx, cy = _centroid(wleaf)
        if _in_water(cx, cy, warped_lakes, warped_rivers):
            continue
        member_points[nearest_compound(cx, cy)].extend(wleaf)
        if idx in park_pick:
            park_shapes.append({"name": "公园", "points": [[round(p[0], 1), round(p[1], 1)] for p in wleaf],
                                "trees": [[round(cx + rng.uniform(-18, 18), 1), round(cy + rng.uniform(-16, 16), 1)] for _ in range(4)]})
            continue
        for rect in _rects_from_poly(wleaf, rng):
            tower = rng.random() < 0.16
            name = _building_name(rng, used_names) if (tower or rng.random() < 0.14) else ""
            blocks.append({"points": rect, "shade": rng.randint(0, 3), "tower": tower, "name": name})

    compounds_out = []
    for i, entry in enumerate(compound_defs):
        hull = _convex_hull(member_points[i]) if member_points[i] else []
        if len(hull) < 3:
            continue
        compounds_out.append({"name": entry["name"],
                              "points": [[round(x, 1), round(y, 1)] for x, y in hull]})

    # model-named landmark buildings (from the setting), if any
    named_buildings = []
    for entry in (buildings or [])[:20]:
        if isinstance(entry, dict) and entry.get("name"):
            named_buildings.append({"name": str(entry["name"])[:24],
                                    "x": round(_clamp(_float(entry.get("x"), width / 2), 40, width - 40), 1),
                                    "y": round(_clamp(_float(entry.get("y"), height / 2), 40, height - 40), 1)})
    named_buildings = _dedupe(named_buildings, lambda b: b["name"])

    model_roads = _norm_roads(roads, index, width, height, rng)
    roads_out = _dedupe(model_roads or generated_roads, lambda r: r["name"])
    metro_out = _norm_transit(metro, index, width, height, rng, _METRO_COLORS, ["地铁1号线", "地铁2号线"], network=streets) or _fallback_metro(width, height, streets)
    bus_out = _norm_transit(bus, index, width, height, rng, _BUS_COLORS, ["公交1路", "公交2路"], network=streets) or _fallback_bus(index, streets)
    parks_out = _dedupe(_norm_parks(parks, width, height) or park_shapes, lambda p: p["name"])

    world_map = {
        "kind": "fictional",
        "title": title or (city or country or "世界") + "地图",
        "width": width, "height": height, "country": country, "city": city,
        "streets": street_only, "roads": roads_out,
        "blocks": blocks, "parks": parks_out, "compounds": compounds_out,
        "named_buildings": named_buildings,
        "water": list(water or []), "lakes": lakes, "rivers": rivers,
        "districts": _norm_districts(districts, names, width, height),
        "metro": metro_out, "bus": bus_out,
        "locations": placed, "actors": list(actors), "edges": _location_edges(placed),
    }
    return _warp_map(world_map, width, height, phase)
