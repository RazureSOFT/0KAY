def _blob(cx, cy, radius, rng, name="湖"):
    points = []
    phase = rng.uniform(0, math.tau)
    for index in range(18):
        angle = math.tau * index / 18
        r = radius * (0.78 + 0.32 * math.sin(3 * angle + phase) + 0.12 * math.sin(5 * angle + phase * 2))
        points.append([round(cx + math.cos(angle) * r, 1), round(cy + math.sin(angle) * r, 1)])
    return {"name": name, "points": points, "label": [round(cx, 1), round(cy, 1)], "r": round(radius, 1)}


def _river(rng, width, height):
    start_x = rng.choice([width * 0.08, width * 0.92])
    start_y = rng.uniform(height * 0.1, height * 0.35) if start_x < width / 2 else rng.uniform(height * 0.65, height * 0.9)
    points = []
    for step in [i / 8 for i in range(9)]:
        x = start_x + (width - 2 * start_x) * step + math.sin(step * math.tau) * width * 0.06
        y = start_y + (height - 2 * start_y) * step + math.cos(step * math.tau) * height * 0.05
        points.append([round(x, 1), round(y, 1)])
    return {"name": "河", "points": points}


def _norm_points(pts, width, height):
    if not isinstance(pts, list) or len(pts) < 2:
        return None
    out = [[round(_clamp(_float(p[0], width / 2), 0, width), 1), round(_clamp(_float(p[1], height / 2), 0, height), 1)]
           for p in pts if isinstance(p, (list, tuple)) and len(p) >= 2]
    return out if len(out) >= 2 else None


def _resolve(ref, index):
    if isinstance(ref, dict):
        if ref.get("x") is not None:
            return (_float(ref.get("x"), 0.0), _float(ref.get("y"), 0.0))
        ref = ref.get("at") or ref.get("place") or ref.get("name")
    if isinstance(ref, str):
        return index.get(ref.strip())
    return None


def _norm_lakes(water, rng, width, height):
    lakes = []
    for entry in (water or []):
        if isinstance(entry, dict) and entry.get("kind") != "river" and entry.get("x") is not None:
            lakes.append(_blob(_clamp(_float(entry.get("x"), width / 2), 80, width - 80),
                               _clamp(_float(entry.get("y"), height / 2), 80, height - 80),
                               _clamp(_float(entry.get("r"), 80), 40, 150), rng,
                               str(entry.get("name") or "湖")[:12]))
    if not lakes:
        lakes.append(_blob(rng.uniform(width * 0.58, width * 0.8), rng.uniform(height * 0.6, height * 0.8), rng.uniform(60, 90), rng))
    return lakes


def _norm_rivers(water, rng, width, height):
    rivers = []
    for entry in (water or []):
        if isinstance(entry, dict) and entry.get("kind") == "river":
            pts = _norm_points(entry.get("points"), width, height)
            if pts:
                rivers.append({"name": str(entry.get("name") or "河")[:12], "points": pts})
    if not rivers:
        rivers.append(_river(rng, width, height))
    return rivers


def _norm_districts(raw, names, width, height):
    out = []
    if isinstance(raw, list):
        for entry in raw[:8]:
            if not isinstance(entry, dict):
                continue
            name = str(entry.get("name") or "").strip()
            if not name:
                continue
            out.append({"name": name[:16],
                        "x": round(_clamp(_float(entry.get("x"), width / 2), 70, width - 70), 1),
                        "y": round(_clamp(_float(entry.get("y"), height / 2), 70, height - 70), 1),
                        "r": round(_clamp(_float(entry.get("r"), 220), 140, 340), 1)})
    if not out:
        pool = [str(n) for n in (names or []) if str(n).strip()] or _DEFAULT_DISTRICTS
        count = min(6, len(pool))
        for index in range(count):
            angle = -math.pi / 2 + math.tau * index / count
            out.append({"name": pool[index][:16],
                        "x": round(width / 2 + math.cos(angle) * width * 0.28, 1),
                        "y": round(height / 2 + math.sin(angle) * height * 0.28, 1),
                        "r": round(min(width, height) * 0.24, 1)})
    return out


def _route_through(waypoints, rng):
    if len(waypoints) < 2:
        return waypoints
    points = [waypoints[0]]
    for a, b in zip(waypoints, waypoints[1:]):
        points.append([round((a[0] + b[0]) / 2 + rng.uniform(-24, 24), 1),
                       round((a[1] + b[1]) / 2 + rng.uniform(-24, 24), 1)])
        points.append([round(b[0], 1), round(b[1], 1)])
    return points


def _norm_roads(raw, index, width, height, rng):
    out = []
    for entry in (raw or [])[:20]:
        if isinstance(entry, str):
            entry = {"name": entry}
        if not isinstance(entry, dict):
            continue
        name = str(entry.get("name") or "").strip()[:20]
        kind = str(entry.get("kind") or "arterial").strip().lower()
        if kind not in _ROAD_KINDS:
            kind = "arterial"
        path = _norm_points(entry.get("points"), width, height)
        if not path:
            a = _resolve(entry.get("from"), index)
            b = _resolve(entry.get("to"), index)
            if a and b:
                path = _route_through([[a[0], a[1]], [b[0], b[1]]], rng)
        if path:
            out.append({"name": name, "kind": kind, "points": path})
    return out


def _norm_transit(raw, index, width, height, rng, colors, fallback_names, network=None):
    out = []
    for i, line in enumerate((raw or [])[:8]):
        if not isinstance(line, dict):
            continue
        name = str(line.get("name") or (fallback_names[i] if i < len(fallback_names) else f"线路{i + 1}"))[:20]
        stops = []
        for entry in (line.get("stations") or line.get("stops") or [])[:16]:
            label, point = "", None
            if isinstance(entry, str):
                label, point = entry.strip(), index.get(entry.strip())
            elif isinstance(entry, dict):
                label = str(entry.get("name") or "").strip()
                point = _resolve(entry, index)
            if point:
                stops.append({"name": label[:16], "x": round(_clamp(point[0], 0, width), 1), "y": round(_clamp(point[1], 0, height), 1)})
        stops = _dedupe(stops, lambda s: s["name"] or f"{s['x']},{s['y']}")
        if len(stops) < 2:
            continue
        points = _route_along_streets(stops, network) if network else _route_through([[s["x"], s["y"]] for s in stops], rng)
        # The colour ends up in an inline style on the panel, so only accept a
        # literal hex value; anything else (model-provided) falls back.
        color = str(line.get("color") or "").strip()
        if not _COLOR_RE.match(color):
            color = colors[i % len(colors)]
        out.append({"name": name, "color": color,
                    "points": points, "stations": stops, "stops": stops})
    return _dedupe(out, lambda line: line["name"])


def _norm_parks(raw, width, height):
    out = []
    for entry in (raw or [])[:6]:
        if isinstance(entry, str):
            entry = {"name": entry}
        if not isinstance(entry, dict):
            continue
        name = str(entry.get("name") or "公园")[:16]
        pts = _norm_points(entry.get("points"), width, height)
        if not pts and entry.get("x") is not None:
            cx = _clamp(_float(entry.get("x"), width / 2), 60, width - 60)
            cy = _clamp(_float(entry.get("y"), height / 2), 60, height - 60)
            r = _clamp(_float(entry.get("r"), 70), 40, 130)
            pts = [[round(cx + math.cos(math.tau * k / 8) * r, 1), round(cy + math.sin(math.tau * k / 8) * r * 0.8, 1)] for k in range(8)]
        if pts and len(pts) >= 3:
            out.append({"name": name, "points": pts, "trees": []})
    return out


