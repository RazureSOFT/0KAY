/**
 * Generate the shared motion tokens from the Material 3 spring definitions.
 *
 * M3 Expressive replaced the easing+duration system with springs: a token is a
 * stiffness / damping-ratio pair, and the UI applies it to a property. The values
 * below are the published ones from androidx compose-material3
 * `ExpressiveMotionTokens` / `StandardMotionTokens` (v0_14_0). They are copied
 * here, not invented, so the CSS and the reference stay comparable.
 *
 * A spring has no duration, and CSS `linear()` has no time component — it only
 * describes a shape. So each token becomes a pair: a sampled progress curve and a
 * duration, both derived from the same physics:
 *
 *   - stiff = stiffness, zeta = damping ratio, mass = 1, initial velocity = 0
 *   - the curve is the normalised displacement of a damped oscillator
 *   - the duration is the settle time, i.e. when the envelope is under 0.2%
 *
 * That threshold is a choice, and it is the only free parameter here. 0.2% is
 * below one device pixel for every UI size in this app, so nothing visibly moves
 * after it.
 *
 * Run with `node scripts/gen-spring-tokens.mjs`. Output goes to
 * `src/styles/spring-tokens.css`, which `theme.css` imports. Do not hand-edit the
 * generated file: the sampling points are not eyeballable.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const outFile = path.resolve(here, '../src/styles/spring-tokens.css')

/** Settle threshold: below this the spring is visually at rest. */
const REST_THRESHOLD = 0.002
/** Samples per curve. 24 keeps the CSS string short and the curve smooth. */
const SAMPLES = 24

/**
 * Damping ratios are shared across a speed ladder, so several tokens resolve to
 * the same curve and differ only in duration. The generator emits one curve per
 * distinct damping ratio instead of one per token — 3 curves covers all 9 tokens.
 */
const TOKENS = [
  // name                      stiffness  damping  space
  { name: 'expressive-fast-spatial',     stiffness: 800,  damping: 0.6, axis: 'spatial' },
  { name: 'expressive-default-spatial',  stiffness: 380,  damping: 0.8, axis: 'spatial' },
  { name: 'expressive-slow-spatial',     stiffness: 200,  damping: 0.8, axis: 'spatial' },
  { name: 'expressive-fast-effects',     stiffness: 3800, damping: 1.0, axis: 'effects' },
  { name: 'expressive-default-effects',  stiffness: 1600, damping: 1.0, axis: 'effects' },
  { name: 'expressive-slow-effects',     stiffness: 800,  damping: 1.0, axis: 'effects' },
  { name: 'standard-fast-spatial',       stiffness: 1400, damping: 0.9, axis: 'spatial' },
  { name: 'standard-default-spatial',    stiffness: 700,  damping: 0.9, axis: 'spatial' },
  { name: 'standard-slow-spatial',       stiffness: 300,  damping: 0.9, axis: 'spatial' },
]

/**
 * Normalised displacement of a unit-mass spring released from 0 toward 1 with no
 * initial velocity, sampled at uniform times over the settle window.
 *
 * Underdamped (zeta < 1) overshoots and oscillates; critically damped (zeta = 1)
 * approaches without crossing 1 — which is what makes effects springs safe for
 * opacity and colour.
 */
function sampleSpring(stiffness, damping, samples = SAMPLES) {
  const wn = Math.sqrt(stiffness)
  const settle = -Math.log(REST_THRESHOLD) / (damping * wn)

  const values = []
  for (let i = 0; i <= samples; i += 1) {
    const t = (settle * i) / samples
    let y
    if (damping < 1) {
      const wd = wn * Math.sqrt(1 - damping * damping)
      y = 1 - Math.exp(-damping * wn * t) * (Math.cos(wd * t) + ((damping * wn) / wd) * Math.sin(wd * t))
    } else {
      y = 1 - Math.exp(-wn * t) * (1 + wn * t)
    }
    values.push(y)
  }

  // Pin the endpoints: the formula is asymptotically 1, never exactly it.
  values[0] = 0
  values[values.length - 1] = 1

  const peak = Math.max(...values)
  return { values, settleMs: Math.round(settle * 1000), peak }
}

function fmt(value) {
  if (value === 0 || value === 1) return String(value)
  return String(Math.round(value * 10000) / 10000)
}

/** One CSS custom property per distinct damping ratio, shared by its tokens. */
const curves = new Map()
const durations = []

for (const token of TOKENS) {
  const { values, settleMs, peak } = sampleSpring(token.stiffness, token.damping)
  const key = `--md-spring-${token.damping === 0.6 ? 'bounce' : token.damping === 0.8 ? 'soft' : token.damping === 0.9 ? 'tight' : 'flat'}`
  if (!curves.has(key)) {
    curves.set(key, { damping: token.damping, peak, values, members: [] })
  }
  curves.get(key).members.push(token.name)
  durations.push({ name: token.name, ms: settleMs, stiffness: token.stiffness, damping: token.damping, axis: token.axis, peak })
}

const lines = []
lines.push('/* Motion tokens, generated by scripts/gen-spring-tokens.mjs — do not edit.')
lines.push(' *')
lines.push(' * Values are the published Material 3 spring definitions')
lines.push(' * (androidx.compose.material3 ExpressiveMotionTokens / StandardMotionTokens, v0_14_0).')
lines.push(' * Each `linear()` below is that spring sampled over its own settle window, and the')
lines.push(' * matching `-dur` variable is that window. Use them as a pair:')
lines.push(' *')
lines.push(' *   transition: transform var(--md-spring-expressive-default-spatial-dur) var(--md-spring-soft);')
lines.push(' *')
lines.push(' * Springs that share a damping ratio share a curve; only the duration differs,')
lines.push(' * because the normalised shape of a damped oscillator depends on zeta alone.')
lines.push(' */')
lines.push(':root {')

lines.push('  /* Springs that allow overshoot — position, size, rotation, corner radius. */')
for (const [key, info] of curves) {
  if (info.damping === 1) continue
  lines.push(`  /* damping ${info.damping} · peak ${info.peak.toFixed(4)} (${((info.peak - 1) * 100).toFixed(1)}% overshoot) */`)
  lines.push(`  /* used by: ${info.members.join(', ')} */`)
  lines.push(`  ${key}: linear(${info.values.map(fmt).join(', ')});`)
}

lines.push('')
lines.push('  /* Springs that must not overshoot — colour and opacity only.')
lines.push('     A critically damped spring cannot pass its target, so alpha never exceeds 1. */')
for (const [key, info] of curves) {
  if (info.damping !== 1) continue
  lines.push(`  /* damping ${info.damping} · peak ${info.peak.toFixed(4)} (no overshoot) */`)
  lines.push(`  /* used by: ${info.members.join(', ')} */`)
  lines.push(`  ${key}: linear(${info.values.map(fmt).join(', ')});`)
}

lines.push('')
lines.push('  /* Settle time per token. Pair each curve with its own duration. */')
for (const d of durations) {
  lines.push(`  /* ${d.axis} · stiffness ${d.stiffness} · damping ${d.damping} · ~${d.ms}ms settled · peak ${(d.peak * 100).toFixed(1)}% */`)
  lines.push(`  --md-spring-${d.name}-dur: ${d.ms}ms;`)
}

lines.push('}')
lines.push('')
lines.push('/* Reduced motion keeps the colour/opacity result and removes the travel.')
lines.push(' * Zeroing the durations is enough because the curves are progress-only: at 1ms')
lines.push(' * they resolve to their end state, which is what "no motion" should look like.')
lines.push(' * `animation` is already flattened globally in theme.css. */')
lines.push('@media (prefers-reduced-motion: reduce) {')
lines.push('  :root {')
for (const d of durations) {
  lines.push(`    --md-spring-${d.name}-dur: 1ms;`)
}
lines.push('  }')
lines.push('}')
lines.push('')

fs.writeFileSync(outFile, lines.join('\n'), 'utf8')

console.log(`wrote ${path.relative(process.cwd(), outFile)}`)
console.log(`${curves.size} curves, ${durations.length} durations`)
for (const d of durations) {
  console.log(`  ${d.name.padEnd(28)} ${String(d.ms).padStart(4)}ms  peak ${(d.peak * 100).toFixed(1)}%`)
}